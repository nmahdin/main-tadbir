type Period='monthly'|'quarterly'|'annual';
type QuoteLike={status:string;remaining_seconds:number};
type OrderLike={status:string;review_remaining_seconds:number};
type OwnerScope={kind:'personal'}|{kind:'organization';organizationId:number};
type OwnedSnapshot={organization_id:number|null;personal_workspace_id:number|null};
export const PERIODS:Period[]=['monthly','quarterly','annual'];
export const PERIOD_LABELS:Record<Period,string>={monthly:'ماهانه',quarterly:'سه‌ماهه',annual:'سالانه'};
export const convertible=(q:QuoteLike)=>q.status==='open'&&q.remaining_seconds>0;
export const cancellable=(o:OrderLike)=>o.status==='in_review'&&o.review_remaining_seconds>0;
export const owns=(v:OwnedSnapshot,s:OwnerScope)=>s.kind==='organization'?v.organization_id===s.organizationId:v.organization_id===null&&v.personal_workspace_id!==null;
